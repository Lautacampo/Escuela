import { pool } from "../../config/db.js";

const ANIO_DE_MODULO = {
  1: 1,
  2: 1,
  3: 2,
  4: 2,
  5: 3,
  6: 3,
};

let esquemaInicializado = false;

export const asegurarEsquemaPlanEstudio = async () => {
  if (esquemaInicializado) return;

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.plan_estudio (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      titulo character varying(150) NOT NULL,
      resolucion character varying(100) NOT NULL,
      orientacion character varying(100) DEFAULT 'Ciencias Sociales' NOT NULL,
      anio_inicio integer DEFAULT 2026 NOT NULL,
      estado character varying(20) DEFAULT 'Vigente' NOT NULL,
      activo boolean DEFAULT true NOT NULL,
      creado_en timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT plan_estudio_estado_check CHECK (estado IN ('Vigente', 'Inactivo'))
    );

    CREATE TABLE IF NOT EXISTS public.plan_estudio_materia_modulo (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      plan_estudio_id integer NOT NULL REFERENCES public.plan_estudio(id) ON DELETE CASCADE,
      modulo_id integer NOT NULL REFERENCES public.modulo(id) ON DELETE CASCADE,
      materia_id integer NOT NULL REFERENCES public.materia(id) ON DELETE CASCADE,
      UNIQUE (plan_estudio_id, modulo_id, materia_id)
    );
  `);

  // Si todavía no hay ningún plan cargado, sembramos el plan inicial a partir de materia_modulo
  const { rowCount } = await pool.query("SELECT 1 FROM plan_estudio LIMIT 1");
  if (rowCount === 0) {
    const ins = await pool.query(
      `INSERT INTO plan_estudio (titulo, resolucion, orientacion, anio_inicio, estado, activo)
       VALUES ($1, $2, $3, $4, 'Vigente', true)
       RETURNING id`,
      [
        "Bachiller en Ciencias Sociales",
        "Decreto N.º 3795-ME-2021",
        "Ciencias Sociales",
        2021,
      ],
    );
    const planId = ins.rows[0].id;

    await pool.query(
      `INSERT INTO plan_estudio_materia_modulo (plan_estudio_id, modulo_id, materia_id)
       SELECT $1, modulo_id, materia_id FROM materia_modulo
       ON CONFLICT DO NOTHING`,
      [planId],
    );
  }

  esquemaInicializado = true;
};

const armarEstructuraPlan = async (planRow) => {
  if (!planRow) return null;

  const { rows } = await pool.query(
    `SELECT m.id AS "moduloId",
            m.numero_leyenda AS "moduloNombre",
            COALESCE(
              (SELECT DISTINCT c.anio_curso
                 FROM curso_modulo cm
                 JOIN curso c ON c.id = cm.curso_id
                WHERE cm.modulo_id = m.id
                LIMIT 1),
              CASE
                WHEN m.id IN (1, 2) THEN 1
                WHEN m.id IN (3, 4) THEN 2
                ELSE 3
              END
            ) AS anio,
            COALESCE(
              json_agg(
                json_build_object('id', ma.id, 'nombre', ma.nombre)
                ORDER BY ma.nombre
              ) FILTER (WHERE ma.id IS NOT NULL),
              '[]'::json
            ) AS materias
       FROM modulo m
       LEFT JOIN plan_estudio_materia_modulo pemm
         ON pemm.modulo_id = m.id AND pemm.plan_estudio_id = $1
       LEFT JOIN materia ma ON ma.id = pemm.materia_id
      GROUP BY m.id, m.numero_leyenda
      ORDER BY m.id`,
    [planRow.id],
  );

  const aniosMap = new Map();
  for (const r of rows) {
    const anio = r.anio || ANIO_DE_MODULO[r.moduloId] || 1;
    if (!aniosMap.has(anio)) {
      aniosMap.set(anio, {
        anio,
        modulos: [],
      });
    }
    aniosMap.get(anio).modulos.push({
      id: r.moduloId,
      nombre: `Módulo ${r.moduloNombre}`,
      numeroLeyenda: r.moduloNombre,
      materias: r.materias,
    });
  }

  return {
    id: planRow.id,
    titulo: planRow.titulo,
    resolucion: planRow.resolucion,
    orientacion: planRow.orientacion,
    anioInicio: planRow.anio_inicio,
    estado: planRow.estado,
    activo: planRow.activo,
    anios: Array.from(aniosMap.values()).sort((a, b) => a.anio - b.anio),
  };
};

// #35 - GET /api/plan-estudio/actual (devuelve el plan vigente + lista de planes inactivos por baja lógica)
export const obtenerPlanes = async () => {
  await asegurarEsquemaPlanEstudio();

  const { rows } = await pool.query(
    `SELECT id, titulo, resolucion, orientacion, anio_inicio, estado, activo
       FROM plan_estudio
      ORDER BY activo DESC, id DESC`,
  );

  const planesDetallados = [];
  for (const row of rows) {
    planesDetallados.push(await armarEstructuraPlan(row));
  }

  const planActual = planesDetallados.find((p) => p.activo) ?? null;
  const planesInactivos = planesDetallados.filter((p) => !p.activo);

  return {
    planActual,
    planesInactivos,
    historial: planesDetallados,
  };
};

export const buscarPlanPorId = async (id) => {
  await asegurarEsquemaPlanEstudio();
  const { rows } = await pool.query(
    `SELECT id, titulo, resolucion, orientacion, anio_inicio, estado, activo
       FROM plan_estudio
      WHERE id = $1`,
    [id],
  );
  return rows[0] ? await armarEstructuraPlan(rows[0]) : null;
};

// #36 - POST /api/plan-estudio (Crea un nuevo plan vigente y pasa el anterior a Inactivo por baja lógica)
export const crearPlanEstudio = async ({
  titulo,
  resolucion,
  orientacion = "Ciencias Sociales",
  anioInicio = 2026,
  modulos = [],
}) => {
  await asegurarEsquemaPlanEstudio();
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    // Baja lógica automática de cualquier plan que estuviera vigente antes
    await client.query(
      `UPDATE plan_estudio
          SET activo = false,
              estado = 'Inactivo'
        WHERE activo = true`,
    );

    const ins = await client.query(
      `INSERT INTO plan_estudio (titulo, resolucion, orientacion, anio_inicio, estado, activo)
       VALUES ($1, $2, $3, $4, 'Vigente', true)
       RETURNING id, titulo, resolucion, orientacion, anio_inicio, estado, activo`,
      [
        titulo.trim(),
        resolucion.trim(),
        orientacion.trim(),
        Number(anioInicio),
      ],
    );
    const nuevoPlan = ins.rows[0];

    // Sincronizamos también materia_modulo para que el resto del sistema use el nuevo plan activo
    await client.query("DELETE FROM materia_modulo");

    for (const mod of modulos) {
      const moduloId = Number(mod.moduloId);
      const materiasIds = Array.isArray(mod.materiasIds) ? mod.materiasIds : [];

      for (const matId of materiasIds) {
        await client.query(
          `INSERT INTO plan_estudio_materia_modulo (plan_estudio_id, modulo_id, materia_id)
           VALUES ($1, $2, $3)
           ON CONFLICT (plan_estudio_id, modulo_id, materia_id) DO NOTHING`,
          [nuevoPlan.id, moduloId, Number(matId)],
        );

        await client.query(
          `INSERT INTO materia_modulo (materia_id, modulo_id)
           VALUES ($1, $2)
           ON CONFLICT (materia_id, modulo_id) DO NOTHING`,
          [Number(matId), moduloId],
        );
      }
    }

    await client.query("COMMIT");
    return await armarEstructuraPlan(nuevoPlan);
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
};

// #37 - DELETE /api/plan-estudio/:id (Baja lógica: cambia estado a 'Inactivo' y activo = false)
export const desactivarPlanEstudio = async (id) => {
  await asegurarEsquemaPlanEstudio();
  const { rows } = await pool.query(
    `UPDATE plan_estudio
        SET activo = false,
            estado = 'Inactivo'
      WHERE id = $1
      RETURNING id, titulo, resolucion, orientacion, anio_inicio, estado, activo`,
    [id],
  );
  return rows[0] ? await armarEstructuraPlan(rows[0]) : null;
};

// #38 - GET /api/materias
export const listarMaterias = async () => {
  const { rows } = await pool.query(
    `SELECT ma.id,
            ma.nombre,
            COALESCE(
              ARRAY_AGG(mm.modulo_id ORDER BY mm.modulo_id) FILTER (WHERE mm.modulo_id IS NOT NULL),
              ARRAY[]::int[]
            ) AS "modulosIds"
       FROM materia ma
       LEFT JOIN materia_modulo mm ON mm.materia_id = ma.id
      GROUP BY ma.id, ma.nombre
      ORDER BY ma.nombre`,
  );
  return rows;
};

// #39 - POST /api/materias
export const crearMateria = async ({ nombre, modulosIds = [] }) => {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");

    const existente = await client.query(
      `SELECT id, nombre FROM materia WHERE LOWER(TRIM(nombre)) = LOWER(TRIM($1)) LIMIT 1`,
      [nombre],
    );
    if (existente.rowCount > 0) {
      const error = new Error("Ya existe una materia con ese nombre");
      error.code = "23505";
      throw error;
    }

    const { rows } = await client.query(
      `INSERT INTO materia (nombre) VALUES ($1) RETURNING id, nombre`,
      [nombre.trim()],
    );
    const nuevaMateria = rows[0];

    for (const modId of modulosIds) {
      await client.query(
        `INSERT INTO materia_modulo (materia_id, modulo_id)
         VALUES ($1, $2)
         ON CONFLICT (materia_id, modulo_id) DO NOTHING`,
        [nuevaMateria.id, Number(modId)],
      );
    }

    await client.query("COMMIT");
    return { ...nuevaMateria, modulosIds };
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
};

// #40 - GET /api/ciclo-lectivo
export const listarCiclosLectivos = async () => {
  const { rows } = await pool.query(
    `SELECT id, anio FROM ciclo_lectivo ORDER BY anio DESC`,
  );
  const maxAnio = rows[0]?.anio ?? 2026;
  return rows.map((r) => ({
    id: r.id,
    anio: r.anio,
    activo: r.anio === maxAnio,
    estado: r.anio === maxAnio ? "Activo" : "Cerrado",
  }));
};
