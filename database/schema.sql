CREATE FUNCTION public.validar_rol_disjunto()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    parent_id integer;
    sibling_exists boolean;
    sibling_table text;
BEGIN
    EXECUTE format(
        'SELECT id FROM public.%I WHERE id = $1 FOR UPDATE',
        TG_ARGV[0]
    )
    INTO parent_id
    USING NEW.id;

    IF parent_id IS NULL THEN
        RAISE EXCEPTION 'No existe el registro padre % con id %', TG_ARGV[0], NEW.id;
    END IF;

    FOREACH sibling_table IN ARRAY TG_ARGV[1:] LOOP
        EXECUTE format(
            'SELECT EXISTS (SELECT 1 FROM public.%I WHERE id = $1)',
            sibling_table
        )
        INTO sibling_exists
        USING NEW.id;

        IF sibling_exists THEN
            RAISE EXCEPTION 'El id % ya tiene otro subtipo en %', NEW.id, sibling_table;
        END IF;
    END LOOP;

    RETURN NEW;
END;
$$;

CREATE FUNCTION public.validar_completitud_persona(p_id integer)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.persona WHERE id = p_id)
       AND (
           (SELECT count(*) FROM (
               SELECT id FROM public.alumno WHERE id = p_id
               UNION ALL
               SELECT id FROM public.personal WHERE id = p_id
           ) AS subtipos) <> 1
       ) THEN
        RAISE EXCEPTION 'La persona % debe ser exactamente alumno o personal', p_id;
    END IF;
END;
$$;

CREATE FUNCTION public.validar_completitud_personal(p_id integer)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.personal WHERE id = p_id)
       AND (
           (SELECT count(*) FROM (
               SELECT id FROM public.docente WHERE id = p_id
               UNION ALL
               SELECT id FROM public.directivo WHERE id = p_id
               UNION ALL
               SELECT id FROM public.preceptor WHERE id = p_id
           ) AS subtipos) <> 1
       ) THEN
        RAISE EXCEPTION 'El personal % debe ser exactamente docente, directivo o preceptor', p_id;
    END IF;
END;
$$;

CREATE FUNCTION public.verificar_completitud_herencia()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP <> 'DELETE' THEN
        IF TG_ARGV[0] = 'persona' THEN
            PERFORM public.validar_completitud_persona(NEW.id);
        ELSE
            PERFORM public.validar_completitud_personal(NEW.id);
        END IF;
    END IF;

    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.id IS DISTINCT FROM NEW.id) THEN
        IF TG_ARGV[0] = 'persona' THEN
            PERFORM public.validar_completitud_persona(OLD.id);
        ELSE
            PERFORM public.validar_completitud_personal(OLD.id);
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

