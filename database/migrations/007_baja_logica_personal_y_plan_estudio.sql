-- 007_baja_logica_personal_y_plan_estudio.sql
--
-- 1. Baja lógica de docentes y preceptores.
--    Un docente o preceptor que deja de trabajar por un tiempo (licencia,
--    pedido particular) pasa a INACTIVO: no inicia sesión y no se borra
--    ningún dato. El directivo puede reactivarlo o, estando inactivo,
--    eliminarlo definitivamente.
--
-- 2. Plan de estudios.
--    Las tablas del plan y la columna alumno.plan_estudio_id las creaba el
--    backend al iniciar. Quedan acá para que el esquema se pueda reproducir
--    solo con schema.sql y las migraciones. El backend mantiene la misma
--    verificación al iniciar por si la base todavía no tiene esta migración.
--
-- Es idempotente: se puede ejecutar más de una vez.
--   psql "<cadena de conexión>" -f database/migrations/007_baja_logica_personal_y_plan_estudio.sql

BEGIN;

-- 1. Estado de docentes y preceptores --------------------------------------
ALTER TABLE public.docente   ADD COLUMN IF NOT EXISTS activo boolean NOT NULL DEFAULT true;
ALTER TABLE public.preceptor ADD COLUMN IF NOT EXISTS activo boolean NOT NULL DEFAULT true;

-- 2. Plan de estudios ------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.plan_estudio (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo character varying(150) NOT NULL,
    resolucion character varying(100) NOT NULL,
    orientacion character varying(100) DEFAULT 'Ciencias Sociales' NOT NULL,
    anio_inicio integer DEFAULT 2026 NOT NULL,
    estado character varying(20) DEFAULT 'Vigente' NOT NULL,
    activo boolean DEFAULT true NOT NULL,
    creado_en timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT plan_estudio_estado_check CHECK (estado IN ('Vigente', 'Inactivo'))
);

CREATE TABLE IF NOT EXISTS public.plan_estudio_materia_modulo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_estudio_id integer NOT NULL REFERENCES public.plan_estudio(id) ON DELETE CASCADE,
    modulo_id integer NOT NULL REFERENCES public.modulo(id) ON DELETE CASCADE,
    materia_id integer NOT NULL REFERENCES public.materia(id) ON DELETE CASCADE,
    UNIQUE (plan_estudio_id, modulo_id, materia_id)
);

-- Plan inicial, solo si todavía no hay ninguno.
INSERT INTO public.plan_estudio (titulo, resolucion, orientacion, anio_inicio, estado, activo)
SELECT 'Bachiller en Ciencias Sociales', 'Decreto N.º 3795-ME-2021', 'Ciencias Sociales', 2021, 'Vigente', true
 WHERE NOT EXISTS (SELECT 1 FROM public.plan_estudio);

INSERT INTO public.plan_estudio_materia_modulo (plan_estudio_id, modulo_id, materia_id)
SELECT p.id, mm.modulo_id, mm.materia_id
  FROM public.materia_modulo mm
 CROSS JOIN (SELECT id FROM public.plan_estudio ORDER BY id LIMIT 1) p
 WHERE NOT EXISTS (SELECT 1 FROM public.plan_estudio_materia_modulo)
ON CONFLICT DO NOTHING;

-- Plan al que pertenece cada alumno (se fija en su primera matrícula).
ALTER TABLE public.alumno
    ADD COLUMN IF NOT EXISTS plan_estudio_id integer REFERENCES public.plan_estudio(id);

-- Alumnos ya matriculados sin plan: el vigente (o el último registrado).
UPDATE public.alumno a
   SET plan_estudio_id = (SELECT id FROM public.plan_estudio
                           ORDER BY activo DESC, id DESC
                           LIMIT 1)
 WHERE a.plan_estudio_id IS NULL
   AND EXISTS (SELECT 1 FROM public.cursada_modulo cm WHERE cm.alumno_id = a.id);

COMMIT;
